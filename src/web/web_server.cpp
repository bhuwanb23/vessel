static void openBrowser(const std::string& url) {
#ifdef _WIN32
    ShellExecuteA(NULL, "open", url.c_str(), NULL, NULL, SW_SHOWNORMAL);
#elif __APPLE__
    std::system(("open " + url).c_str());
#else
    std::system(("xdg-open " + url + " &").c_str());
#endif
}

