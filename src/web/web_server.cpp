static json hardwareToJson(const HardwareSpec& hw) {
    json j;
    j["gpu_name"] = hw.gpu_name;
    j["vram_total"] = hw.vram_total_bytes;
    j["vram_used"] = hw.vram_total_bytes - hw.vram_free_bytes;
    j["vram_free"] = hw.vram_free_bytes;
    j["ram_total"] = hw.ram_total_bytes;
    j["ram_used"] = hw.ram_total_bytes - hw.ram_free_bytes;
    j["ram_free"] = hw.ram_free_bytes;
    j["temp"] = hw.gpu_temp_celsius;
    j["gpu_bw"] = hw.gpu_bandwidth_gbs;
    j["gpu_tflops"] = hw.gpu_tflops_fp16;
    j["ram_bw"] = hw.ram_bandwidth_gbs;
    j["nvme_seq"] = hw.nvme_sequential_mbs;
    j["nvme_rand"] = hw.nvme_random_4k_mbs;
    j["platform"] = hw.gpu_name.empty() ? "CPU" : hw.gpu_name;
    j["fingerprint"] = hw.hardware_fingerprint;
    j["unified_memory"] = hw.is_unified_memory;
    return j;
}

static json predictionToJson(const Prediction& p, const StrategyConfig& s) {
    json j;
    j["vram"] = p.memory_vram_bytes;
    j["ram"] = p.memory_ram_bytes;
    j["tps"] = p.tokens_per_sec;
    j["ttft"] = p.ttft_ms;
    j["viable"] = p.viable;
    j["confidence"] = (p.confidence == PredictionConfidence::HIGH) ? "HIGH" :
                      (p.confidence == PredictionConfidence::MEDIUM) ? "MEDIUM" : "LOW";

    // Placement
    switch (s.placement) {
        case PlacementStrategy::FULL_GPU:       j["placement"] = "FULL_GPU"; break;
        case PlacementStrategy::GPU_CPU_SPLIT:  j["placement"] = "GPU_CPU_SPLIT"; break;
        case PlacementStrategy::CPU_ONLY:       j["placement"] = "CPU_ONLY"; break;
        case PlacementStrategy::HOT_COLD_SPLIT: j["placement"] = "HOT_COLD_SPLIT"; break;
        case PlacementStrategy::LAYER_STREAM:   j["placement"] = "LAYER_STREAM"; break;
        default:                               j["placement"] = "UNKNOWN"; break;
    }
    j["gpu_layers"] = s.gpu_layers;
    j["ctx"] = s.context_length;
    j["kv"] = s.kv_quant_bits;

    // MoE range
    if (p.is_moe_range) {
        j["tps_best"] = p.tok_s_best;
        j["tps_worst"] = p.tok_s_worst;
        j["tps_expected"] = p.tok_s_expected;
    }
    return j;
}

static std::string starsString(double score) {
    int full = (int)(score / 2.0 + 0.5);
    if (full > 5) full = 5;
    if (full < 0) full = 0;
    std::string s;
    for (int i = 0; i < full; i++) s += "\xe2\x98\x85";  // ★
    for (int i = full; i < 5; i++) s += "\xe2\x98\x86";  // ☆
    return s;
}

