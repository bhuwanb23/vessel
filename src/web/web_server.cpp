// GET /api/models/local
static void handleLocalModels(const httplib::Request&, httplib::Response& res) {
    // Scan common model directories for .gguf files
    json models = json::array();
    const char* dirs[] = {
        "models", "../models", "./models",
        "C:/dev/models", "C:/models"
    };
    for (const char* dir : dirs) {
        if (!fs::exists(dir)) continue;
        for (const auto& entry : fs::directory_iterator(dir)) {
            if (!entry.is_regular_file()) continue;
            std::string ext = entry.path().extension().string();
            // Case-insensitive compare
            for (auto& c : ext) c = (char)tolower(c);
            if (ext != ".gguf") continue;
            json mj;
            mj["path"] = entry.path().string();
            mj["filename"] = entry.path().filename().string();
            mj["size_bytes"] = entry.file_size();
            mj["size_gb"] = entry.file_size() / 1e9;
            models.push_back(mj);
        }
    }
    json data;
    data["models"] = models;
    data["count"] = models.size();
    sendJson(res, 200, makeSuccess(data));
}

// POST /api/download
static void handleDownloadStart(const httplib::Request& req, httplib::Response& res) {
    json body;
    try { body = json::parse(req.body); } catch (...) {
        sendJson(res, 400, makeError("INVALID_JSON", "Request body is not valid JSON"));
        return;
    }

    std::string model_url = body.value("model_url", "");
    if (model_url.empty()) {
        sendJson(res, 400, makeError("MISSING_PARAM", "model_url is required"));
        return;
    }

    // Check if a task is already running
    {
        std::lock_guard<std::mutex> lock(g_task_mutex);
        if (g_task_running) {
            sendJson(res, 409, makeError("BUSY", "Another task is in progress",
                "Active: " + g_active_task_type + " (" + g_active_task_id + ")"));
            return;
        }
        g_task_running = true;
        g_active_task_type = "download";
        g_active_task_id = generateTaskId("dl");
    }

    json data;
    data["task_id"] = g_active_task_id;
    data["stream_url"] = "/api/download/" + g_active_task_id + "/progress";
    sendJson(res, 200, makeSuccess(data));
}

// GET /api/download/:id/progress (SSE)
static void handleDownloadProgress(const httplib::Request& req, httplib::Response& res) {
    std::string task_id;
    auto it = req.path_params.find("id");
    if (it != req.path_params.end()) task_id = it->second;

    if (task_id != g_active_task_id) {
        sendJson(res, 404, makeError("TASK_NOT_FOUND", "No active download with this ID"));
        return;
    }

    sendSSEHeader(res);

    std::string captured_id = task_id;
    res.set_chunked_content_provider("text/event-stream",
        [captured_id](size_t, httplib::DataSink& sink) -> bool {
            if (!g_task_running || g_active_task_id != captured_id) {
                std::string msg = "event: complete\ndata: {\"message\": \"Download complete\"}\n\n";
                sink.write(msg.c_str(), msg.size());
                return false;
            }

            std::string msg = "event: progress\ndata: {\"status\": \"downloading\", \"message\": \"In progress...\"}\n\n";
            bool ok = sink.write(msg.c_str(), msg.size());
            std::this_thread::sleep_for(std::chrono::milliseconds(500));
            return ok;
        });
}

