static json makeSuccess(const json& data) {
    json j;
    j["success"] = true;
    j["data"] = data;
    j["error"] = nullptr;
    return j;
}

static json makeError(const std::string& code, const std::string& message, const std::string& details = "") {
    json j;
    j["success"] = false;
    j["data"] = nullptr;
    j["error"] = { {"code", code}, {"message", message}, {"details", details} };
    return j;
}

static void sendJson(httplib::Response& res, int status, const json& envelope) {
    res.status = status;
    res.set_header("Access-Control-Allow-Origin", "*");
    res.set_header("Content-Type", "application/json");
    res.set_content(envelope.dump(), "application/json");
}

static void sendSSEHeader(httplib::Response& res) {
    res.set_header("Access-Control-Allow-Origin", "*");
    res.set_header("Content-Type", "text/event-stream");
    res.set_header("Cache-Control", "no-cache");
    res.set_header("Connection", "keep-alive");
}

